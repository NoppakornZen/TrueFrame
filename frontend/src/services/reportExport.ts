// Export the verification result as a real, downloadable audit report —
// fully offline, generated in the browser. Produces a self-contained HTML
// report (printable to PDF from the browser) or a JSON file for downstream systems.

import { DeliveryCase, Evidence, PolicyRule, DecisionResult } from '../types';
import { buildRequirements } from './requirements';

export interface AuditReport {
  generatedAt: string;
  generator: string;
  deliveryCase: DeliveryCase | null;
  decision: DecisionResult;
  evidence: Array<{
    id: string;
    name: string;
    type: string;
    status: string;
    capturedAt: string;
    confidence?: number;
    recommendation?: string;
    findings: string[];
    metadata: Record<string, unknown>;
  }>;
  policies: Array<{
    id: string;
    name: string;
    enabled: boolean;
    minimumConfidence: number;
    requiredEvidenceTypes: string[];
  }>;
}

export function buildAuditReport(
  deliveryCase: DeliveryCase | null,
  evidence: Evidence[],
  policies: PolicyRule[],
  decision: DecisionResult
): AuditReport {
  return {
    generatedAt: new Date().toISOString(),
    generator: 'TrueFrame Evidence Decision Engine v1.0 (offline)',
    deliveryCase,
    decision,
    evidence: evidence.map((e) => ({
      id: e.id,
      name: e.name,
      type: e.type,
      status: e.status,
      capturedAt: e.capturedAt,
      confidence: e.aiAnalysis?.confidence,
      recommendation: e.aiAnalysis?.recommendation,
      findings: e.aiAnalysis?.findings ?? [],
      metadata: (e.metadata ?? {}) as Record<string, unknown>,
    })),
    policies: policies.map((p) => ({
      id: p.id,
      name: p.name,
      enabled: p.enabled,
      minimumConfidence: p.minimumConfidence,
      requiredEvidenceTypes: p.requiredEvidenceTypes,
    })),
  };
}

function escapeHtml(s: unknown): string {
  return String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

const decisionColor: Record<string, string> = {
  accept: '#16a34a',
  reject: '#dc2626',
  needs_review: '#d97706',
};

/** Standalone, printable HTML audit report — no external assets, opens offline. */
export function reportToHtml(report: AuditReport): string {
  const d = report.decision;
  const color = decisionColor[d.decision] ?? '#334155';
  const c = report.deliveryCase;
  const requirementRows = buildRequirements(
    report.evidence.map((e) => ({
      id: e.id,
      type: e.type as Evidence['type'],
      status: e.status as Evidence['status'],
      name: e.name,
      description: '',
      capturedAt: e.capturedAt,
      uploadedBy: '',
      metadata: e.metadata,
    }))
  )
    .map(
      (row) => `      <tr>
        <td>${escapeHtml(row.label)}</td>
        <td>${escapeHtml(row.status.replace('_', ' '))}</td>
        <td>${escapeHtml(row.sources.join(', ') || '—')}</td>
        <td>${escapeHtml(row.reason)}</td>
      </tr>`
    )
    .join('\n');

  const evidenceRows = report.evidence
    .map(
      (e) => `      <tr>
        <td>${escapeHtml(e.name)}<br /><span class="muted">${escapeHtml(e.type)} • ${escapeHtml(
          new Date(e.capturedAt).toLocaleString()
        )}</span></td>
        <td>${escapeHtml(e.status.toUpperCase())}</td>
        <td>${e.confidence !== undefined ? (e.confidence * 100).toFixed(1) + '%' : '—'}</td>
        <td>${escapeHtml(e.recommendation ?? '—')}</td>
        <td><ul>${e.findings.map((f) => `<li>${escapeHtml(f)}</li>`).join('')}</ul></td>
      </tr>`
    )
    .join('\n');

  const policyRows = report.policies
    .map(
      (p) => `      <tr>
        <td>${escapeHtml(p.name)}</td>
        <td>${p.enabled ? 'Active' : 'Disabled'}</td>
        <td>${(p.minimumConfidence * 100).toFixed(0)}%</td>
        <td>${escapeHtml(p.requiredEvidenceTypes.join(', '))}</td>
      </tr>`
    )
    .join('\n');

  const conflictBlocks = d.conflicts.length
    ? d.conflicts
        .map(
          (c) => `      <div class="conflict">
        <strong>${escapeHtml(c.severity.toUpperCase())} — ${escapeHtml(c.type)}</strong>
        <p>${escapeHtml(c.description)}</p>
        <p class="muted">Suggested resolution: ${escapeHtml(c.suggestedResolution)}</p>
      </div>`
        )
        .join('\n')
    : '      <p class="muted">No conflicts detected.</p>';

  // Honesty footer: name AI exactly when it was used, otherwise keep the
  // offline sentence verbatim (tests and the demo both rely on it).
  const aiEvidence = report.evidence.find((e) => e.metadata?.analysisSource === 'ai');
  const aiModel = String((aiEvidence?.metadata?.aiCondition as any)?.model ?? 'vision');
  const footerNote = aiEvidence
    ? `Generated by ${escapeHtml(report.generator)}. Barcode and certificate analysis was performed
    locally in the browser; photo condition observations were generated by AI vision (${escapeHtml(
      aiModel
    )}) — treat as advisory and verify by eye.`
    : `Generated offline by ${escapeHtml(report.generator)}. All barcode, certificate and image
    analysis was performed locally in the browser — no external AI service was contacted.`;

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<title>TrueFrame Verification Report — ${escapeHtml(c?.id ?? 'CASE')}</title>
<style>
  body { font-family: -apple-system, Segoe UI, Roboto, Arial, sans-serif; color: #0f172a; margin: 32px; }
  h1 { margin: 0 0 4px; font-size: 22px; }
  .muted { color: #64748b; font-size: 12px; }
  table { width: 100%; border-collapse: collapse; margin-top: 12px; font-size: 13px; }
  th, td { border: 1px solid #cbd5e1; padding: 8px; text-align: left; vertical-align: top; }
  th { background: #f1f5f9; }
  ul { margin: 0; padding-left: 16px; }
  .verdict { border: 2px solid ${color}; border-radius: 8px; padding: 16px; margin: 20px 0; }
  .verdict .value { font-size: 32px; font-weight: 700; color: ${color}; }
  .conflict { border-left: 4px solid #dc2626; background: #fef2f2; padding: 10px 12px; margin-bottom: 8px; }
  .conflict p { margin: 4px 0 0; font-size: 13px; }
  .meta { display: flex; gap: 24px; flex-wrap: wrap; font-size: 13px; margin-top: 8px; }
  footer { margin-top: 32px; border-top: 1px solid #cbd5e1; padding-top: 12px; font-size: 11px; color: #64748b; }
</style>
</head>
<body>
  <h1>TrueFrame — Evidence-Based Delivery Verification</h1>
  <p class="muted">Audit report generated ${escapeHtml(new Date(report.generatedAt).toLocaleString())} • ${escapeHtml(report.generator)}</p>

  <div class="meta">
    <div><span class="muted">Case</span><br />${escapeHtml(c?.id ?? '—')}</div>
    <div><span class="muted">Part</span><br />${escapeHtml(c?.partName ?? '—')}</div>
    <div><span class="muted">Part Number</span><br />${escapeHtml(c?.partNumber ?? '—')}</div>
    <div><span class="muted">Supplier</span><br />${escapeHtml(c?.supplier ?? '—')}</div>
    <div><span class="muted">Destination</span><br />${escapeHtml(c?.destination ?? '—')}</div>
  </div>

  <div class="verdict">
    <div class="value">${escapeHtml(d.decision.toUpperCase().replace('_', ' '))}</div>
    <p>Confidence ${(d.confidence * 100).toFixed(1)}% • ${d.evidenceUsed.length} evidence item(s) • ${escapeHtml(
      d.conflicts.length
    )} conflict(s)</p>
  </div>

  <h2>What was checked</h2>
  <table>
    <thead><tr><th>Requirement</th><th>Status</th><th>Sources</th><th>Why</th></tr></thead>
    <tbody>
${requirementRows}
    </tbody>
  </table>

  <h2>Decision reasoning</h2>
  <ul>
${d.reasoning.map((r) => `    <li>${escapeHtml(r)}</li>`).join('\n')}
  </ul>

  <h2>Conflicts</h2>
${conflictBlocks}

  <h2>Evidence</h2>
  <table>
    <tr><th>Item</th><th>Status</th><th>Confidence</th><th>Recommendation</th><th>Findings</th></tr>
${evidenceRows}
  </table>

  <h2>Policies evaluated</h2>
  <table>
    <tr><th>Policy</th><th>State</th><th>Min confidence</th><th>Requires</th></tr>
${policyRows}
  </table>

  <footer>
    ${footerNote}
  </footer>
</body>
</html>`;
}

export function downloadFile(filename: string, content: string, mime: string): void {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  // Revoke on the next tick so the download has definitely started
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
